import type {NextRequest} from 'next/server';
import {NextResponse} from 'next/server';
import {voiceUuid,voiceService,tokenDigest} from '@/lib/intrigue-ai/voice-gate';

type Obj=Record<string,unknown>;
const obj=(v:unknown):Obj=>v&&typeof v==='object'&&!Array.isArray(v)?v as Obj:{};
const str=(v:unknown):string=>typeof v==='string'?v:'';
const respond=(v:unknown,status=200)=>NextResponse.json(v,{status,headers:{'Cache-Control':'no-store'}});

/** Inbound dynamic assistant selection. This is NOT the existing tool/call-history webhook.
 * The Vapi phone MUST have no fixed assistantId, otherwise Vapi never requests this gate.
 * The phone server URL must carry a per-number bearer credential, generated by INTRIGUE.
 */
export async function POST(req:NextRequest){
 if(Number(req.headers.get('content-length')||0)>65536)return respond({error:'Invalid call request.'},413);
 const match=/^Bearer ([a-f0-9]{64})$/i.exec(req.headers.get('authorization')||'');
 if(!match)return respond({error:'Voice gate authentication required.'},401);
 let body:Obj;
 try{const raw=await req.text();if(raw.length>65536)return respond({error:'Invalid call request.'},413);body=obj(JSON.parse(raw));}
 catch{return respond({error:'Invalid call request.'},400);}
 const message=obj(body.message);
 if(message.type!=='assistant-request')return new NextResponse(null,{status:204,headers:{'Cache-Control':'no-store'}});
 const call=obj(message.call),phone=obj(call.phoneNumber),eventPhone=obj(message.phoneNumber);
 const callId=str(call.id);
 const phoneId=str(call.phoneNumberId)||str(phone.id)||str(eventPhone.id);
 if(!voiceUuid.test(callId)||!voiceUuid.test(phoneId))return respond({error:'Invalid phone or call identifier.'},400);
 try{
  const db=voiceService();
  // Workspace identity comes ONLY from server-side token+phone mapping, never webhook metadata.
  const hashed=tokenDigest(match[1]);
  const {data:route,error:lookupError}=await db.from('intrigue_ai_voice_routes')
   .select('workspace_id,assistant_id,provider_mode,active')
   .eq('phone_number_id',phoneId).eq('token_sha256',hashed).eq('active',true).maybeSingle();
  if(lookupError)return respond({error:'Voice service unavailable.'},503);
  if(!route)return respond({error:'Voice gate authorization denied.'},401);
  const {data:admission,error}=await db.rpc('intrigue_ai_voice_admit',{
   p_workspace:route.workspace_id,p_phone_number:phoneId,
   p_assistant:route.assistant_id,p_call:callId,p_token_sha256:hashed});
  if(error||!admission)return respond({error:'Our receptionist is temporarily unavailable. Please contact the business directly.'},503);
  if(admission.approved===true)return respond({assistantId:route.assistant_id});
  if(admission.reason==='voice_allowance_exhausted'){
   const {error:noticeError}=await db.rpc('intrigue_ai_budget_notice_emit',{
    p_workspace:route.workspace_id,p_kind:'voice'});
   if(noticeError)console.warn('[VOICE_BUDGET_NOTICE_FAILED]');
   return respond({error:'Our AI receptionist is temporarily unavailable. Please call back or contact the business directly.'});
  }
  return respond({error:'Our receptionist is unavailable. Please contact the business directly.'});
 }catch{return respond({error:'Our receptionist is temporarily unavailable. Please contact the business directly.'},503);}
}
