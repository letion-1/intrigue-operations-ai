-- Record why a reviewer changed a status, without granting users access to
-- internal notes. Not an erasure log and does not execute deletion.
CREATE TABLE IF NOT EXISTS public.intrigue_rc22_review_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id uuid NOT NULL REFERENCES public.intrigue_rc2_requests(id) ON DELETE RESTRICT,
  previous_status text NOT NULL,
  new_status text NOT NULL,
  reviewer_identifier text NOT NULL CHECK (char_length(reviewer_identifier) BETWEEN 2 AND 120),
  internal_note text NOT NULL CHECK (char_length(internal_note) BETWEEN 5 AND 2000),
  recorded_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS intrigue_rc22_review_events_request_idx
  ON public.intrigue_rc22_review_events(request_id, recorded_at DESC);
ALTER TABLE public.intrigue_rc22_review_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.intrigue_rc22_review_events FROM PUBLIC, anon, authenticated;

-- Replace the RC2 intake function, preserving its signature and RPC caller.
-- Serializes concurrent submissions per user, reuses identical pending
-- requests, and rejects overlapping account/company requests of different kind.
CREATE OR REPLACE FUNCTION public.intrigue_rc2_request(
  p_kind text, p_workspace_id uuid DEFAULT NULL
) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_actor uuid := (SELECT auth.uid());
  v_name text;
  v_existing uuid;
  v_id uuid;
BEGIN
  IF v_actor IS NULL THEN
    RAISE EXCEPTION 'Sign in required' USING ERRCODE='28000';
  END IF;
  IF p_kind NOT IN ('account','workspace','workspace_and_account') THEN
    RAISE EXCEPTION 'Invalid request kind' USING ERRCODE='22023';
  END IF;
  IF (p_kind = 'account' AND p_workspace_id IS NOT NULL) OR
     (p_kind <> 'account' AND p_workspace_id IS NULL) THEN
    RAISE EXCEPTION 'Request scope mismatch' USING ERRCODE='22023';
  END IF;

  -- Locks only the current user's Auth row, avoiding duplicate simultaneous
  -- intake and never locking or modifying another tenant's workspace.
  PERFORM 1 FROM auth.users WHERE id = v_actor FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Account not found'; END IF;

  IF p_kind <> 'account' THEN
    SELECT name INTO v_name
    FROM public.workspaces
    WHERE id = p_workspace_id AND owner_id = v_actor;
    IF v_name IS NULL THEN
      RAISE EXCEPTION 'Company ownership not verified' USING ERRCODE='42501';
    END IF;
  END IF;

  SELECT id INTO v_existing
  FROM public.intrigue_rc2_requests
  WHERE requested_by = v_actor
    AND kind = p_kind
    AND workspace_id IS NOT DISTINCT FROM p_workspace_id
    AND status IN ('needs_review','reviewing','processing','workspace_deleted')
  ORDER BY requested_at DESC LIMIT 1;
  IF v_existing IS NOT NULL THEN RETURN v_existing; END IF;

  -- An account request is related to any pending company request by the same
  -- requester. Avoid quietly changing requested scope behind the user's back.
  SELECT id INTO v_existing
  FROM public.intrigue_rc2_requests
  WHERE requested_by = v_actor
    AND status IN ('needs_review','reviewing','processing','workspace_deleted')
    AND (
      p_workspace_id IS NULL OR workspace_id IS NULL OR workspace_id = p_workspace_id
    )
  ORDER BY requested_at DESC LIMIT 1;
  IF v_existing IS NOT NULL THEN
    RAISE EXCEPTION 'An overlapping privacy request already exists. Review or withdraw the previous request before submitting another.'
      USING ERRCODE='23505';
  END IF;

  INSERT INTO public.intrigue_rc2_requests (
    requested_by, workspace_id, workspace_label, kind, status, public_message
  ) VALUES (
    v_actor, p_workspace_id, v_name, p_kind, 'needs_review',
    'Request received. No data has been erased. An authorized reviewer will assess next steps.'
  ) RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;
REVOKE ALL ON FUNCTION public.intrigue_rc2_request(text,uuid)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.intrigue_rc2_request(text,uuid) TO authenticated;

-- User-controlled withdrawal, pending review only. Cannot undo actual erasure
-- nor cancel work that has moved into reviewing or processing.
CREATE OR REPLACE FUNCTION public.intrigue_rc22_withdraw_request(
  p_request_id uuid, p_confirmation text
) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_actor uuid := (SELECT auth.uid());
  v_request public.intrigue_rc2_requests%ROWTYPE;
BEGIN
  IF v_actor IS NULL THEN
    RAISE EXCEPTION 'Sign in required' USING ERRCODE='28000';
  END IF;
  IF p_confirmation IS DISTINCT FROM ('WITHDRAW ' || p_request_id::text) THEN
    RAISE EXCEPTION 'Withdrawal confirmation mismatch' USING ERRCODE='22023';
  END IF;
  SELECT * INTO v_request
  FROM public.intrigue_rc2_requests
  WHERE id = p_request_id AND requested_by = v_actor
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Request not found' USING ERRCODE='42501'; END IF;
  IF v_request.status <> 'needs_review' THEN
    RAISE EXCEPTION 'Only requests awaiting review can be withdrawn' USING ERRCODE='23514';
  END IF;
  UPDATE public.intrigue_rc2_requests
  SET status = 'withdrawn', completed_at = now(), status_updated_at = now(),
      public_message = 'Request withdrawn by the account holder before review. No erasure was performed.'
  WHERE id = p_request_id AND requested_by = v_actor AND status = 'needs_review';
  RETURN p_request_id;
END;
$$;
REVOKE ALL ON FUNCTION public.intrigue_rc22_withdraw_request(uuid,text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.intrigue_rc22_withdraw_request(uuid,text)
  TO authenticated;

-- Internal operator review only. Not executable by app users. This can mark
-- a request UNDER REVIEW or close it without erasure with a documented reason.
-- It cannot mark erasure complete or execute any delete operation.
CREATE OR REPLACE FUNCTION public.intrigue_rc22_operator_review(
  p_request_id uuid,
  p_next_status text,
  p_reviewer_identifier text,
  p_internal_note text,
  p_public_message text
) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_request public.intrigue_rc2_requests%ROWTYPE;
BEGIN
  IF p_reviewer_identifier IS NULL OR char_length(trim(p_reviewer_identifier)) NOT BETWEEN 2 AND 120
    OR p_internal_note IS NULL OR char_length(trim(p_internal_note)) NOT BETWEEN 5 AND 2000
    OR p_public_message IS NULL OR char_length(trim(p_public_message)) NOT BETWEEN 10 AND 1200 THEN
    RAISE EXCEPTION 'Reviewer identity, reason, and public response are required';
  END IF;
  SELECT * INTO v_request FROM public.intrigue_rc2_requests
  WHERE id = p_request_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unknown request'; END IF;
  IF NOT (
    (v_request.status = 'needs_review' AND p_next_status = 'reviewing')
    OR (v_request.status = 'reviewing' AND p_next_status IN ('needs_review','rejected'))
  ) THEN
    RAISE EXCEPTION 'Invalid review transition. No erasure execution is supported here.';
  END IF;
  UPDATE public.intrigue_rc2_requests
  SET status = p_next_status,
      status_updated_at = now(),
      public_message = p_public_message,
      operator_note = p_internal_note,
      completed_at = CASE WHEN p_next_status = 'rejected' THEN now() ELSE NULL END
  WHERE id = p_request_id;
  INSERT INTO public.intrigue_rc22_review_events (
    request_id, previous_status, new_status, reviewer_identifier, internal_note
  ) VALUES (
    p_request_id, v_request.status, p_next_status, p_reviewer_identifier, p_internal_note
  );
END;
$$;
REVOKE ALL ON FUNCTION public.intrigue_rc22_operator_review(uuid,text,text,text,text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.intrigue_rc22_operator_review(uuid,text,text,text,text)
  TO service_role;

COMMIT;
