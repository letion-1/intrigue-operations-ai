BEGIN;

-- Track withdrawal and manual review states; leave existing rows unchanged.
ALTER TABLE public.intrigue_rc2_requests
  ADD COLUMN IF NOT EXISTS public_message text;
ALTER TABLE public.intrigue_rc2_requests
  ADD COLUMN IF NOT EXISTS status_updated_at timestamptz NOT NULL DEFAULT now();

-- The RC2 migration uses PostgreSQL's autogenerated status constraint name.
-- Stop if an unfamiliar constraint exists; never remove unrelated validation.
DO $$
DECLARE v_status_constraints int;
BEGIN
  SELECT count(*) INTO v_status_constraints
  FROM pg_catalog.pg_constraint c
  WHERE c.conrelid = 'public.intrigue_rc2_requests'::regclass
    AND c.contype = 'c' AND pg_catalog.pg_get_constraintdef(c.oid) ILIKE '%status%';
  IF v_status_constraints <> 1 OR NOT EXISTS (
    SELECT 1 FROM pg_catalog.pg_constraint c
    WHERE c.conrelid = 'public.intrigue_rc2_requests'::regclass
      AND c.conname = 'intrigue_rc2_requests_status_check'
  ) THEN
    RAISE EXCEPTION 'Unexpected RC2 status constraint. Stop and inspect schema.';
  END IF;
END $$;

ALTER TABLE public.intrigue_rc2_requests
  DROP CONSTRAINT intrigue_rc2_requests_status_check;
ALTER TABLE public.intrigue_rc2_requests
  ADD CONSTRAINT intrigue_rc2_requests_status_check
    CHECK (status IN (
      'needs_review','reviewing','processing','workspace_deleted',
      'completed','rejected','failed','withdrawn'
    ));

-- The existing authenticated SELECT grant was table-wide. Narrow it so
-- internal operator_note cannot be fetched through a direct API query.
REVOKE ALL ON public.intrigue_rc2_requests FROM PUBLIC, anon, authenticated;
GRANT SELECT (
  id, requested_by, workspace_id, workspace_label, kind, status,
  requested_at, response_due_at, completed_at, public_message, status_updated_at
