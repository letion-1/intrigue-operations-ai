-- Queue a single event at most once per workflow/event_key. No cross-workspace argument.
CREATE OR REPLACE FUNCTION public.intrigue_v17_enqueue(
  p_workflow_id uuid, p_event_key text, p_payload jsonb DEFAULT '{}'::jsonb
)
RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_workflow public.intrigue_v17_workflows%ROWTYPE; v_id uuid; v_status text;
BEGIN
 IF p_event_key IS NULL OR char_length(p_event_key) NOT BETWEEN 1 AND 240
    OR p_payload IS NULL OR jsonb_typeof(p_payload) <> 'object'
    OR pg_catalog.octet_length(p_payload::text) > 32768 THEN
    RAISE EXCEPTION 'Invalid workflow event';
 END IF;
 SELECT * INTO v_workflow FROM public.intrigue_v17_workflows
   WHERE id = p_workflow_id AND enabled = true;
 IF NOT FOUND THEN RAISE EXCEPTION 'Workflow missing or disabled'; END IF;
 v_status := CASE WHEN v_workflow.requires_approval THEN 'awaiting_approval' ELSE 'queued' END;
 INSERT INTO public.intrigue_v17_runs
    (workspace_id, workflow_id, event_key, payload, status, max_attempts)
 VALUES (v_workflow.workspace_id, v_workflow.id, p_event_key, p_payload,
         v_status, v_workflow.max_attempts)
 ON CONFLICT (workflow_id, event_key) DO NOTHING
 RETURNING id INTO v_id;
 IF v_id IS NULL THEN
   SELECT id INTO v_id FROM public.intrigue_v17_runs
     WHERE workflow_id = p_workflow_id AND event_key = p_event_key;
 ELSE
   INSERT INTO public.intrigue_v17_run_events(workspace_id,run_id,event_type)
   VALUES(v_workflow.workspace_id,v_id,'enqueued');
 END IF;
 RETURN v_id;
END; $$;

-- This RPC must ONLY be invoked by an authenticated owner/admin-checking server route.
-- No browser grants and no UI route in V17.1A; the CLI is for staging developers.
CREATE OR REPLACE FUNCTION public.intrigue_v17_approve(
    p_run_id uuid, p_approved_by uuid
)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_workspace uuid;
BEGIN
 IF p_approved_by IS NULL THEN RAISE EXCEPTION 'Actor required'; END IF;
 UPDATE public.intrigue_v17_runs
 SET status='queued', approved_at=now(), approved_by=p_approved_by,
     updated_at=now()
 WHERE id=p_run_id AND status='awaiting_approval'
 RETURNING workspace_id INTO v_workspace;
 IF NOT FOUND THEN RETURN false; END IF;
 INSERT INTO public.intrigue_v17_run_events(workspace_id,run_id,event_type,details)
 VALUES(v_workspace,p_run_id,'approved',jsonb_build_object('actor_id',p_approved_by));
 RETURN true;
END; $$;

-- Atomically claim one job with a lease. Competing workers cannot claim the same row.
CREATE OR REPLACE FUNCTION public.intrigue_v17_claim(p_lease_seconds int DEFAULT 120)
RETURNS SETOF public.intrigue_v17_runs
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_run public.intrigue_v17_runs%ROWTYPE;
BEGIN
 IF p_lease_seconds NOT BETWEEN 30 AND 600 THEN
   RAISE EXCEPTION 'Invalid lease duration'; END IF;
 -- Unfinished expired leases that have exhausted retries become dead letters.
 WITH expired AS (
   SELECT id FROM public.intrigue_v17_runs
   WHERE status='running' AND leased_until < now() AND attempts >= max_attempts
   FOR UPDATE SKIP LOCKED LIMIT 100
 )
 UPDATE public.intrigue_v17_runs r
   SET status='dead_letter',lease_token=NULL,leased_until=NULL,
       last_error='Worker lease expired after final attempt',
       finished_at=now(),updated_at=now()
 FROM expired WHERE r.id=expired.id;
 WITH candidate AS (
   SELECT id FROM public.intrigue_v17_runs
   WHERE (
     (status IN ('queued','retry_wait') AND available_at <= now()) OR
     (status='running' AND leased_until < now())
   ) AND attempts < max_attempts
   ORDER BY available_at, created_at
   FOR UPDATE SKIP LOCKED LIMIT 1
 )
 UPDATE public.intrigue_v17_runs r
   SET status='running', attempts=r.attempts+1,
       lease_token=gen_random_uuid(),
       leased_until=now()+pg_catalog.make_interval(secs=>p_lease_seconds),
       updated_at=now()
 FROM candidate
 WHERE r.id=candidate.id
 RETURNING r.* INTO v_run;
 IF NOT FOUND THEN RETURN; END IF;
 INSERT INTO public.intrigue_v17_run_events(workspace_id,run_id,event_type,details)
 VALUES(v_run.workspace_id,v_run.id,'claimed',jsonb_build_object('attempt',v_run.attempts));
 RETURN NEXT v_run;
END; $$;

-- Only the active lease token can finish a run. Expired workers cannot overwrite results.
CREATE OR REPLACE FUNCTION public.intrigue_v17_finish(
 p_run_id uuid, p_lease_token uuid, p_success boolean,
 p_result jsonb DEFAULT '{}'::jsonb, p_error text DEFAULT NULL
)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_run public.intrigue_v17_runs%ROWTYPE; v_next text;
BEGIN
 IF p_success IS NULL OR p_result IS NULL OR pg_catalog.octet_length(p_result::text)>32768 THEN
   RAISE EXCEPTION 'Invalid result'; END IF;
 SELECT * INTO v_run FROM public.intrigue_v17_runs
 WHERE id=p_run_id AND status='running' AND lease_token=p_lease_token
   AND leased_until >= now() FOR UPDATE;
 IF NOT FOUND THEN RETURN 'stale_lease'; END IF;
 v_next := CASE WHEN p_success THEN 'succeeded'
   WHEN v_run.attempts >= v_run.max_attempts THEN 'dead_letter'
   ELSE 'retry_wait' END;
 UPDATE public.intrigue_v17_runs
 SET status=v_next, lease_token=NULL, leased_until=NULL,
     available_at=CASE WHEN v_next='retry_wait'
       THEN now()+pg_catalog.make_interval(secs=>LEAST(3600,30*pg_catalog.power(2,v_run.attempts-1)::int))
       ELSE available_at END,
     result=CASE WHEN p_success THEN p_result ELSE result END,
     last_error=CASE WHEN p_success THEN NULL ELSE left(COALESCE(p_error,'Unknown failure'),300) END,
     finished_at=CASE WHEN v_next IN ('succeeded','dead_letter') THEN now() ELSE NULL END,
     updated_at=now()
 WHERE id=p_run_id;
 INSERT INTO public.intrigue_v17_run_events(workspace_id,run_id,event_type,details)
 VALUES(v_run.workspace_id,p_run_id,v_next,
   jsonb_build_object('attempt',v_run.attempts));
 RETURN v_next;
END; $$;

