-- ADDITIVE ONLY. Apply to an isolated STAGING Supabase project first.
-- No changes to V11 automation_jobs or existing customer/email/calendar tables.
-- Do not use this as the final public API: RPC EXECUTE is restricted to service_role.
BEGIN;

CREATE TABLE IF NOT EXISTS public.intrigue_v17_workflows (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE RESTRICT,
    name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
    trigger_type text NOT NULL DEFAULT 'manual'
      CHECK (trigger_type IN ('manual','scheduled','enquiry.created','quotation.approved','receptionist.missed_call')),
    action_type text NOT NULL DEFAULT 'audit_event'
      CHECK (action_type = 'audit_event'), -- no customer side effects in 17.1A
    enabled boolean NOT NULL DEFAULT false,
    requires_approval boolean NOT NULL DEFAULT true CHECK (requires_approval = true),
    max_attempts int NOT NULL DEFAULT 3 CHECK (max_attempts BETWEEN 1 AND 10),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, workspace_id)
);

CREATE TABLE IF NOT EXISTS public.intrigue_v17_runs (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE RESTRICT,
    workflow_id uuid NOT NULL,
    event_key text NOT NULL CHECK (char_length(event_key) BETWEEN 1 AND 240),
    payload jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(payload) = 'object'),
    status text NOT NULL DEFAULT 'awaiting_approval'
      CHECK (status IN ('awaiting_approval','queued','running','retry_wait','succeeded','dead_letter','cancelled')),
    attempts int NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts int NOT NULL DEFAULT 3 CHECK (max_attempts BETWEEN 1 AND 10),
    available_at timestamptz NOT NULL DEFAULT now(),
    lease_token uuid,
    leased_until timestamptz,
    approved_at timestamptz,
    approved_by uuid,
    last_error text,
    result jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    CONSTRAINT intrigue_v17_runs_workflow_fk
      FOREIGN KEY (workflow_id, workspace_id)
      REFERENCES public.intrigue_v17_workflows(id, workspace_id) ON DELETE RESTRICT,
    UNIQUE (workflow_id, event_key),
    UNIQUE (id, workspace_id)
);

CREATE TABLE IF NOT EXISTS public.intrigue_v17_run_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE RESTRICT,
    run_id uuid NOT NULL,
    event_type text NOT NULL,
    details jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT intrigue_v17_events_run_workspace_fk
      FOREIGN KEY (run_id, workspace_id)
      REFERENCES public.intrigue_v17_runs(id, workspace_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS intrigue_v17_run_claim_idx
  ON public.intrigue_v17_runs(available_at, created_at)
  WHERE status IN ('queued', 'retry_wait', 'running');
CREATE INDEX IF NOT EXISTS intrigue_v17_runs_workspace_idx
  ON public.intrigue_v17_runs(workspace_id, created_at DESC);
CREATE INDEX IF NOT EXISTS intrigue_v17_events_run_idx
  ON public.intrigue_v17_run_events(run_id, created_at);

ALTER TABLE public.intrigue_v17_workflows ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.intrigue_v17_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.intrigue_v17_run_events ENABLE ROW LEVEL SECURITY;

