-- INTRIGUE Operations AI V17.3A
-- Add-only CSV customer imports. No existing records are updated or deleted.
-- Requires existing public.workspaces, workspace_memberships, customers tables.
-- Run once in the intended Supabase project after a verified backup.
BEGIN;

CREATE TABLE IF NOT EXISTS public.intrigue_v173_contact_import_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE RESTRICT,
  actor_id uuid NOT NULL,
  total_rows integer NOT NULL,
  imported_rows integer NOT NULL,
  skipped_duplicate_rows integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.intrigue_v173_contact_import_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.intrigue_v173_contact_import_audit FROM PUBLIC, anon, authenticated;

CREATE INDEX IF NOT EXISTS intrigue_v173_customer_email_lookup_idx
  ON public.customers (workspace_id, pg_catalog.lower(pg_catalog.btrim(email)))
  WHERE email IS NOT NULL;

CREATE OR REPLACE FUNCTION public.intrigue_v173_import_customers(
  p_workspace_id uuid,
  p_rows jsonb,
  p_apply boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_actor uuid := auth.uid();
  v_row jsonb;
  v_count integer;
  v_row_number integer := 0;
  v_new integer := 0;
  v_dup integer := 0;
  v_invalid integer := 0;
  v_email text;
  v_name text;
  v_phone text;
  v_company text;
  v_vehicle text;
  v_seen text[] := ARRAY[]::text[];
  v_details jsonb := '[]'::jsonb;
  v_state text;
BEGIN
  IF v_actor IS NULL OR p_workspace_id IS NULL THEN
    RAISE EXCEPTION 'Authenticated workspace member required';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.workspaces w
    WHERE w.id = p_workspace_id
      AND (
        w.owner_id = v_actor
        OR EXISTS (
          SELECT 1 FROM public.workspace_memberships m
          WHERE m.workspace_id = w.id AND m.user_id = v_actor
            AND m.role IN ('owner', 'admin')
        )
      )
  ) THEN
    RAISE EXCEPTION 'Owner/Admin permissions required for customer import';
  END IF;
  IF p_rows IS NULL OR pg_catalog.jsonb_typeof(p_rows) <> 'array' THEN
    RAISE EXCEPTION 'Contact import requires an array';
  END IF;
  v_count := pg_catalog.jsonb_array_length(p_rows);
  IF v_count < 1 OR v_count > 200 THEN
    RAISE EXCEPTION 'Import between 1 and 200 rows per batch';
  END IF;

  -- Concurrent imports for this workspace serialize on the workspace record.
  -- Direct manual CRM inserts still follow their own existing RLS rules.
  IF p_apply THEN
    PERFORM 1 FROM public.workspaces WHERE id = p_workspace_id FOR UPDATE;
  END IF;

  FOR v_row IN SELECT value FROM pg_catalog.jsonb_array_elements(p_rows) LOOP
    v_row_number := v_row_number + 1;
    v_state := 'new';
    IF pg_catalog.jsonb_typeof(v_row) <> 'object' THEN
      v_state := 'invalid';
    ELSE
      v_name := pg_catalog.btrim(coalesce(v_row->>'full_name',''));
      v_email := pg_catalog.lower(pg_catalog.btrim(coalesce(v_row->>'email','')));
      v_phone := pg_catalog.btrim(coalesce(v_row->>'phone',''));
      v_company := pg_catalog.btrim(coalesce(v_row->>'company_name',''));
      v_vehicle := pg_catalog.btrim(coalesce(v_row->>'vehicle',''));
      IF pg_catalog.char_length(v_name) NOT BETWEEN 2 AND 150
        OR pg_catalog.char_length(v_email) > 254
        OR v_email !~* '^[a-z0-9._%+\-]+@[a-z0-9.\-]+\.[a-z]{2,}$'
        OR pg_catalog.char_length(v_phone) > 40
        OR (v_phone <> '' AND v_phone !~ '^[+0-9(). \-]{5,40}$')
        OR pg_catalog.char_length(v_company) > 200
        OR pg_catalog.char_length(v_vehicle) > 250
        OR pg_catalog.left(v_name,1) IN ('=', '+', '-', '@')
      THEN
        v_state := 'invalid';
      ELSIF v_email = ANY(v_seen) THEN
        v_state := 'duplicate_in_file';
      ELSE
        v_seen := pg_catalog.array_append(v_seen,v_email);
        IF EXISTS (
          SELECT 1 FROM public.customers c
          WHERE c.workspace_id = p_workspace_id
            AND pg_catalog.lower(pg_catalog.btrim(c.email)) = v_email
        ) THEN
          v_state := 'already_in_crm';
        END IF;
      END IF;
    END IF;
    IF v_state = 'invalid' THEN
      v_invalid := v_invalid + 1;
    ELSIF v_state = 'new' THEN
      v_new := v_new + 1;
      IF p_apply THEN
        INSERT INTO public.customers(workspace_id,full_name,email,phone,company_name,vehicle)
        VALUES (
          p_workspace_id,v_name,v_email,
          NULLIF(v_phone,''),NULLIF(v_company,''),
          NULLIF(v_vehicle,'')
        );
      END IF;
    ELSE
      v_dup := v_dup + 1;
    END IF;
    IF v_row_number <= 20 THEN
      v_details := v_details || pg_catalog.jsonb_build_array(
        pg_catalog.jsonb_build_object('row',v_row_number + 1,'status',v_state)
      );
    END IF;
  END LOOP;

  -- Reject the entire batch on invalid rows, including any earlier inserts.
  -- Postgres will roll back the function statement transaction on exception.
  IF p_apply AND v_invalid > 0 THEN
    RAISE EXCEPTION 'Import blocked: % invalid contacts. Fix the file and preview again.',v_invalid;
  END IF;
  IF p_apply THEN
    INSERT INTO public.intrigue_v173_contact_import_audit(
      workspace_id, actor_id, total_rows, imported_rows, skipped_duplicate_rows
    ) VALUES (p_workspace_id,v_actor,v_count,v_new,v_dup);
  END IF;
  RETURN pg_catalog.jsonb_build_object(
    'preview',NOT p_apply,'total_rows',v_count,'new_rows',v_new,
    'duplicate_rows',v_dup,'invalid_rows',v_invalid,'details',v_details,
    'message',CASE WHEN p_apply THEN 'Contacts added. No existing contacts changed.'
      ELSE 'Preview only. Nothing saved.' END
  );
END;
$$;

REVOKE ALL ON FUNCTION public.intrigue_v173_import_customers(uuid,jsonb,boolean)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.intrigue_v173_import_customers(uuid,jsonb,boolean)
  TO authenticated;

COMMIT;
NOTIFY pgrst, 'reload schema';
