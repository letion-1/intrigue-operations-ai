const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const root = process.cwd();
function loadTs(rel) {
  const file = path.join(root,rel);
  const source = fs.readFileSync(file,'utf8');
  const transpiled = ts.transpileModule(source,{fileName:file,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
  const mod = new Module(file,module);
  mod.filename=file;
  mod.paths=Module._nodeModulePaths(path.dirname(file));
  const old=Module._extensions['.ts'];
  Module._extensions['.ts']=(target,filename)=> {
    const src=fs.readFileSync(filename,'utf8');
    target._compile(ts.transpileModule(src,{fileName:filename,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,filename);
  };
  try{mod._compile(transpiled,file);return mod.exports;}finally{if(old)Module._extensions['.ts']=old;else delete Module._extensions['.ts'];}
}
const {extractVapiSummary}=loadTs('lib/intrigue-vapi-summary.ts');
const {callRow}=loadTs('lib/intrigue-vapi-call-history.ts');
const base={id:'00000000-0000-4000-8000-000000000001',assistantId:'69d66b3d-b2c8-442c-95bb-1b1d86e636e5',createdAt:'2026-11-13T14:00:00.000Z',status:'ended',type:'webCall'};
const output=(name,result)=>({artifact:{structuredOutputs:{'71f9e201-0000-4000-8000-000000000001':{name,result}}}});
test('structured summary object extracted from Vapi artifact',()=>{
 const call={...base,...output('INTRIGUE Call Summary',{summary:'Caller asked to book a meeting. Booking tool confirmed the event.',customerRequest:'Consultation on Monday',outcome:'Meeting booked',followUpRequired:false})};
 const result=callRow(call,false);
 assert.match(result.summary,/Caller asked to book a meeting/);
 assert.match(result.summary,/Outcome: Meeting booked/);
 assert.match(result.summary,/Follow-up required: No/);
 assert.equal(result.transcript,null);
});
test('plain string structured result is supported',()=>{
 assert.equal(extractVapiSummary(output('Call Summary','  Summary generated by Vapi.  ')),'Summary generated by Vapi.');
});
test('legacy analysis is prioritized and supported',()=>{
 assert.equal(extractVapiSummary({...output('INTRIGUE Call Summary','Modern'),analysis:{summary:'Legacy provider summary'}}),'Legacy provider summary');
});
test('never infer summary from a booking tool or unrelated structured output',()=>{
 assert.equal(extractVapiSummary({...base,artifact:{toolCalls:[{name:'google_book_appointment',result:{booked:true}}]}}),null);
 assert.equal(extractVapiSummary(output('Payment Card Data',{summary:'private information'})),null);
});
test('malformed, empty or non-string summaries are ignored safely',()=>{
 assert.equal(extractVapiSummary(output('INTRIGUE Call Summary',{summary:''})),null);
 assert.equal(extractVapiSummary(output('INTRIGUE Call Summary',{summary:123})),null);
 assert.equal(extractVapiSummary(null),null);
});
test('limits summary length and does not import transcript/recording content',()=>{
 const call={...base,...output('INTRIGUE Call Summary',{summary:'S'.repeat(6000)}),artifact:{...output('INTRIGUE Call Summary',{summary:'S'.repeat(6000)}).artifact,transcript:'SECRET_TRANSCRIPT',recordingUrl:'https://example.com/recording'}};
 const row=callRow(call,false);
 assert.ok(row.summary.length <= 4000);
 assert.equal(row.summary.length,2800);
 assert.equal(row.transcript,null);
 assert.equal(row.summary.includes('SECRET_TRANSCRIPT'),false);
});
test('handles array form of structured outputs',()=>{
 assert.equal(extractVapiSummary({artifact:{structuredOutputs:[{name:'INTRIGUE Call Summary',result:{summary:'From array'}}]}}),'From array');
});
test('existing summary recovery route uses callRow without transcript import',()=>{
 const route=fs.readFileSync(path.join(root,'app/api/receptionist/summaries/route.ts'),'utf8');
 assert.match(route,/callRow\(call,false\)/);
 assert.match(route,/\.update\(\{summary:normalized\.summary\}\)/);
});
